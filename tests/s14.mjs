import { open, gotoTitle } from './lib.mjs';
const { browser, page, errors } = await open();
await page.evaluate(() => window.__potion.getState().updateSettings({ theme: 'dark' }));
await gotoTitle(page, 'Getting Started');
await page.locator('.toggle-arrow').first().click();
const last = page.locator('[data-editable]').nth(1);
await last.click();
await page.keyboard.press('End');
await page.keyboard.press('Enter');
await page.keyboard.type('/');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/dark_slash.png' });
await page.keyboard.press('Escape');
await gotoTitle(page, 'Reading List');
await page.screenshot({ path: 'shots/dark_gallery.png' });
await gotoTitle(page, 'Product Roadmap');
await page.getByText('By status').click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/dark_chart.png' });
console.log(errors);
await browser.close();
