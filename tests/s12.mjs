import { open, gotoTitle } from './lib.mjs';
const { browser, page, errors } = await open();
await page.locator('.nav-item', { hasText: 'Inbox' }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/x_inbox.png' });
await page.locator('.inbox-backdrop').click({ position: { x: 1200, y: 400 } });
await gotoTitle(page, 'Getting Started');
// add an inline comment
const ed = page.locator('[data-editable]').nth(2);
const box = await ed.boundingBox();
await page.mouse.move(box.x + 5, box.y + 10); await page.mouse.down(); await page.mouse.move(box.x + 120, box.y + 10, { steps: 4 }); await page.mouse.up();
await page.waitForTimeout(300);
await page.locator('.inline-toolbar').getByText('Comment').click();
await page.waitForTimeout(200);
await page.keyboard.type('Love this tip!');
await page.keyboard.press('Enter');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/x_comments.png' });
await page.locator('.comments-panel .tb-icon').click();
await page.locator('.topbar-right .tb-icon').last().click();
await page.getByText('Version history').click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/x_history.png' });
await page.keyboard.press('Escape');
await page.locator('.modal-backdrop').click({ position: { x: 10, y: 10 } }).catch(() => {});
await page.locator('.nav-item', { hasText: 'Templates' }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/x_templates.png' });
await page.locator('.modal-backdrop').click({ position: { x: 10, y: 10 } });
await gotoTitle(page, 'Journal');
await page.locator('.db-frame').getByText('A quiet Sunday').click();
await page.waitForTimeout(400);
await page.locator('.peek-top .tb-icon').nth(2).click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/x_center_peek.png' });
console.log(errors);
await browser.close();
