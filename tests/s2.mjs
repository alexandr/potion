const dump = () => page.evaluate(() => {
  const s = window.__potion.getState();
  const recent = s.workspace.privatePages.at(-1);
  const out = [];
  const walk = (id, d) => { const b = s.blocks[id]; out.push('  '.repeat(d) + b.type + ':' + b.text); b.children.forEach((c) => walk(c, d + 1)); };
  walk(recent, 0);
  return out.join('\n');
});
